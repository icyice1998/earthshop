create table staff (
  id            uuid primary key default gen_random_uuid(),
  auth_user_id  uuid unique,                      -- login identity (Supabase auth.users.id or your own)
  login         text not null unique check (login = lower(login)),
  emp_id        text,
  display_name  text not null,
  license_no    text,
  role_label    text,
  is_admin      boolean not null default false,
  active        boolean not null default true,
  work_start    time,
  work_end      time,
  created_at    timestamptz not null default now()
  -- NOTE: no password column. Passwords live in the auth system only (hashed).
);
create table staff_permissions (
  staff_id  uuid not null references staff(id) on delete cascade,
  perm_code text not null references permissions(code),
  primary key (staff_id, perm_code)
);

-- ---------- stock ------------------------------------------------------
create table lots (
  id              bigint generated by default as identity primary key,
  product_id      bigint not null references products(id),
  lot_no          text,                            -- เลขที่หรืออักษรของครั้งที่ผลิต
  exp_date        date,
  received_on     date not null,
  qty_in          int  not null check (qty_in >= 0),
  qty_left        int  not null check (qty_left >= 0),
  unit_cost       numeric(12,4) not null default 0,
  supplier_id     bigint references suppliers(id),
  receipt_line_id bigint,                          -- set after receipt_lines exists (FK below)
  source          text not null default 'receive' check (source in ('receive','opening','adjust','unpack')),
  created_at      timestamptz not null default now()
);
create index lots_product_idx   on lots (product_id, exp_date nulls last, received_on, id) where qty_left > 0;
create index lots_product_all   on lots (product_id);
create index lots_exp_idx       on lots (exp_date) where qty_left > 0;

create type movement_type as enum ('opening','receive','sale','void','adjust','return','return_void','issue','unpack_out','unpack_in','receipt_void','cost_adjust');
create table stock_movements (
  id          bigint generated by default as identity primary key,
  ts          timestamptz not null default now(),
  product_id  bigint not null references products(id),
  lot_id      bigint not null references lots(id),
  type        movement_type not null,
  qty         int not null,                        -- signed: + in, - out
  ref_no      text,                                -- bill / invoice number
  note        text,
  staff_name  text
);
create index stock_movements_lot_idx     on stock_movements (lot_id, ts, id);
create index stock_movements_product_idx on stock_movements (product_id, ts);
create index stock_movements_ref_idx     on stock_movements (ref_no) where ref_no is not null;

-- ---------- buying -----------------------------------------------------
create table purchase_orders (
  id                 bigint generated by default as identity primary key,
  no                 text not null unique,
  supplier_id        bigint references suppliers(id),
  ordered_on         date,
  appoint_receive_on date,
  appoint_pay_on     date,
  amount             numeric(12,2),
  doc_no             text,
  status             text not null default 'open' check (status in ('open','partial','closed','cancel')),
  legacy_status      text,
  note               text,
  staff_name         text,
  created_at         timestamptz not null default now()
);
create index purchase_orders_supplier_idx on purchase_orders (supplier_id, ordered_on);
create table purchase_order_lines (
  id           bigint generated by default as identity primary key,
  po_id        bigint not null references purchase_orders(id) on delete cascade,
  product_id   bigint not null references products(id),
  qty          int not null check (qty > 0),
  unit_cost    numeric(12,4) not null default 0,
  received_qty int not null default 0
);
create index purchase_order_lines_po_idx on purchase_order_lines (po_id);
create index purchase_order_lines_prod_idx on purchase_order_lines (product_id);

create table receipts (
  id            bigint generated by default as identity primary key,
  supplier_id   bigint references suppliers(id),
  invoice_no    text,
  received_on   date not null,
  po_id         bigint references purchase_orders(id),
  subtotal      numeric(12,2) not null default 0,
  discount      numeric(12,2) not null default 0,
  total         numeric(12,2) not null default 0,
  invoice_total numeric(12,2),
  status        text not null default 'ok' check (status in ('ok','void')),
  void_reason   text,
  staff_name    text,
  created_at    timestamptz not null default now()
);
create index receipts_supplier_idx on receipts (supplier_id, lower(invoice_no));
create index receipts_date_idx on receipts (received_on);
create table receipt_lines (
  id            bigint generated by default as identity primary key,
  receipt_id    bigint not null references receipts(id) on delete cascade,
  product_id    bigint not null references products(id),
  qty           int not null check (qty > 0),
  free_qty      int not null default 0 check (free_qty >= 0),
  unit_cost     numeric(12,4) not null default 0,
  line_discount numeric(12,4) not null default 0,
  eff_cost      numeric(12,4) not null default 0,    -- (qty*unit_cost - line_discount) / (qty+free_qty)
  lot_no        text,
  exp_date      date,
  lot_id        bigint references lots(id)
);
create index receipt_lines_receipt_idx on receipt_lines (receipt_id);
create index receipt_lines_product_idx on receipt_lines (product_id);
alter table lots add constraint lots_receipt_line_fk foreign key (receipt_line_id) references receipt_lines(id);

create table supplier_returns (
  id           bigint generated by default as identity primary key,
  return_no    text not null unique,
  supplier_id  bigint references suppliers(id),
  returned_on  date not null,
  refund       numeric(12,2) not null default 0,
  reason       text,
  status       text not null default 'ok' check (status in ('ok','void')),
  staff_name   text
);
create table supplier_return_lines (
  id         bigint generated by default as identity primary key,
  return_id  bigint not null references supplier_returns(id) on delete cascade,
  product_id bigint not null references products(id),
  lot_id     bigint references lots(id),
  qty        int not null check (qty > 0),
  unit_cost  numeric(12,4) not null default 0
);

-- ---------- selling -----------------------------------------------------
create sequence bill_seq;
create table sales (
  id              bigint generated by default as identity primary key,
  bill_no         text not null unique,
  ts              timestamptz not null default now(),
  sale_date       date not null,                      -- local (Asia/Bangkok) date of ts
  customer_id     bigint references customers(id),
  staff_name      text,
  subtotal        numeric(12,2) not null default 0,
  discount        numeric(12,2) not null default 0,
  total           numeric(12,2) not null default 0,
  method          text not null default 'cash' check (method in ('cash','transfer','card','mixed')),
  received        numeric(12,2),
  change_amount   numeric(12,2),
  status          text not null default 'ok' check (status in ('ok','void')),
  void_reason     text,
  voided_at       timestamptz,
  voided_by       text,
  -- buyer (ข.ย.10 / 11 / 13) and prescription (ข.ย.12)
  buyer_name      text, buyer_addr text, buyer_type text,
  rx_prescriber   text, rx_prescriber_addr text,
  rx_user         text, rx_user_age text, rx_user_addr text,
  note            text,
  imported        boolean not null default false,
  created_at      timestamptz not null default now()
);
create index sales_date_idx     on sales (sale_date);
create index sales_ts_idx       on sales (ts);
create index sales_staff_idx    on sales (staff_name, sale_date);
create index sales_customer_idx on sales (customer_id) where customer_id is not null;
create index sales_rx_idx       on sales (sale_date) where rx_prescriber is not null;

create table sale_lines (
  id          bigint generated by default as identity primary key,
  sale_id     bigint not null references sales(id) on delete cascade,
  line_no     int not null,
  product_id  bigint references products(id),          -- null = other income line
  name        text not null,
  unit        text,
  qty         int not null,
  unit_price  numeric(12,2) not null,
  line_discount numeric(12,2) not null default 0,
  line_total  numeric(12,2) not null,                  -- qty * unit_price (before bill discount)
  cost_total  numeric(12,2) not null default 0
);
create index sale_lines_sale_idx    on sale_lines (sale_id);
create index sale_lines_product_idx on sale_lines (product_id);
create table sale_line_lots (
  sale_line_id bigint not null references sale_lines(id) on delete cascade,
  lot_id       bigint not null references lots(id),
  qty          int not null check (qty > 0),
  unit_cost    numeric(12,4) not null default 0,
  primary key (sale_line_id, lot_id)
);
create index sale_line_lots_lot_idx on sale_line_lots (lot_id);

create table daily_closings (
  id           bigint generated by default as identity primary key,
  closing_date date not null unique,
  open_float   numeric(12,2) not null default 0,
  counted_cash numeric(12,2),
  expected_cash numeric(12,2),
  note         text,
  staff_name   text,
  created_at   timestamptz not null default now()
);

