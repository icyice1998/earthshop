create table products (
  id              bigint generated by default as identity primary key,
  code            text not null unique,
  name            text not null,
  generic_name    text,
  category_id     int references categories(id),
  unit            text not null default 'ชิ้น',
  barcode         text,
  location        text,
  reg_no          text,                       -- เลขทะเบียนตำรับยา
  manufacturer    text,                       -- ผู้ผลิต / ผู้นำเข้า (ข.ย.10/11/13)
  pack_size       text,                       -- ขนาดบรรจุ
  supplier_id     bigint references suppliers(id),
  reorder_point   int not null default 0,
  order_qty       int not null default 0,
  exp_warn_days   int not null default 0,     -- 0 = use shop.near_expiry_days
  price1          numeric(12,2) not null default 0,
  price2          numeric(12,2),
  price3          numeric(12,2),
  price4          numeric(12,2),
  price5          numeric(12,2),
  latest_cost     numeric(12,4) not null default 0,
  is_supply       boolean not null default false,   -- consumables (bags, tape...) not sold
  active          boolean not null default true,
  usage_text      text, indication text, warning_text text, storage_text text,
  meal_time       text check (meal_time in ('before','with','after')),
  storage_type    text check (storage_type in ('room','fridge')),
  note            text,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);
create index products_barcode_idx on products (barcode) where barcode is not null and barcode <> '';
create index products_name_idx    on products (lower(name));
create index products_generic_idx on products (lower(generic_name));
create index products_category_idx on products (category_id);

-- free-goods terms: buy N get M free (shown as a hint when receiving)
create table supplier_terms (
  supplier_id bigint not null references suppliers(id) on delete cascade,
  product_id  bigint not null references products(id) on delete cascade,
  buy_qty     int not null check (buy_qty > 0),
  free_qty    int not null check (free_qty > 0),
  primary key (supplier_id, product_id)
);

create table product_drug_types (
  product_id bigint not null references products(id) on delete cascade,
  type_code  text   not null references drug_types(code),
  primary key (product_id, type_code)
);
create index product_drug_types_type_idx on product_drug_types (type_code);

-- kit (ยาชุด): selling 1 kit takes parts from stock
create table product_bundles (
  bundle_id bigint not null references products(id) on delete cascade,
  part_id   bigint not null references products(id),
  qty       int not null check (qty > 0),
  primary key (bundle_id, part_id),
  check (bundle_id <> part_id)
);
-- unpacking (แกะแบ่งขาย): 1 parent unit = ratio child units
create table product_unpack (
  parent_id bigint primary key references products(id) on delete cascade,
  child_id  bigint not null references products(id),
  ratio     int not null check (ratio >= 2)
);
-- reusable usage / label templates per product
create table product_usage_templates (
  id          bigint generated by default as identity primary key,
  product_id  bigint not null references products(id) on delete cascade,
  name        text,
  dosage_th   text, dosage_en text,
  time_th     text, time_en text,
  comment_th  text, comment_en text,
  keep_th     text, keep_en text,
  is_default  boolean not null default false
);

create table customers (
