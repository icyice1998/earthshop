-- =====================================================================
-- Supplies (วัสดุ): issue for use, void an issue.
-- Any active staff member may issue supplies (permission 'supplies' is implied for active staff).
-- Run after 01-07. Safe to run again.
-- =====================================================================
insert into permissions (code, group_name, label, sort) values ('supplies', 'หน้าจอ', 'เบิกวัสดุ', 35) on conflict (code) do nothing;

create table if not exists supply_issues (
  id         bigint generated by default as identity primary key,
  ts         timestamptz not null default now(),
  product_id bigint not null references products(id),
  qty        int not null check (qty > 0),
  cost_total numeric(14,4) not null default 0,
  note       text,
  staff_name text,
  status     text not null default 'ok' check (status in ('ok', 'void')),
  void_by    text,
  void_ts    timestamptz
);
alter table supply_issues enable row level security;
revoke all on supply_issues from anon, authenticated;

-- every active staff member counts as having 'supplies'
create or replace function app.has_perm(p text) returns boolean language sql stable security definer set search_path = public as $$
  select app.is_service()
      or (app.uid() is not null and app.open_mode())
      or exists (
           select 1 from staff s
            where s.auth_user_id = app.uid() and s.active
              and (s.is_admin or (p = 'supplies') or exists (select 1 from staff_permissions sp where sp.staff_id = s.id and sp.perm_code = p)))
      or (app.uid() is not null
          and not exists (select 1 from staff s where s.auth_user_id = app.uid())
          and p = any (array['pos', 'members', 'billsView', 'sellOtc']))
$$;

-- stock levels are needed on the supplies page
create or replace view v_lots as
  select l.id, l.product_id, l.lot_no, l.exp_date, l.received_on, l.qty_in, l.qty_left, l.supplier_id, l.source,
         case when app.has_perm('viewCost') then l.unit_cost end as unit_cost
    from lots l where app.has_perm('stock') or app.has_perm('manage') or app.has_perm('receive') or app.has_perm('pos') or app.has_perm('supplies');

create or replace view v_products as
  select p.id, p.code, p.name, p.generic_name, p.category_id, c.name as category, p.unit, p.barcode, p.location, p.reg_no, p.manufacturer, p.pack_size, p.supplier_id,
         p.reorder_point, p.order_qty, p.exp_warn_days, p.price1, p.price2, p.price3, p.price4, p.price5,
         case when app.has_perm('viewCost') then p.latest_cost end as latest_cost,
         p.is_supply, p.active, p.usage_text, p.indication, p.warning_text, p.storage_text, p.meal_time, p.storage_type, p.note,
         coalesce((select array_agg(type_code order by type_code) from product_drug_types d where d.product_id = p.id), '{}') as drug_types,
         app.stock_of(p.id) as stock_qty
    from products p left join categories c on c.id = p.category_id
   where app.has_perm('pos') or app.has_perm('stock') or app.has_perm('manage') or app.has_perm('receive') or app.has_perm('supplies');
grant select on v_products to authenticated;

create or replace view v_supply_issues as
  select i.id, i.ts, i.product_id, i.qty, i.note, i.staff_name, i.status, i.void_by, i.void_ts,
         case when app.has_perm('viewCost') then i.cost_total end as cost_total
    from supply_issues i where app.has_perm('supplies');
grant select on v_supply_issues to authenticated;
grant select on v_lots to authenticated;

create or replace function issue_supply(p_product bigint, p_qty int, p_note text default null) returns bigint language plpgsql security definer set search_path = public as $$
declare prod products; v_id bigint; v_cost numeric := 0; t record; v_ts timestamptz := now();
begin
  perform app.check_perm('supplies');
  select * into prod from products where id = p_product; if not found then raise exception 'ไม่พบวัสดุ'; end if;
  if not prod.is_supply then raise exception 'เบิกใช้ได้เฉพาะวัสดุ'; end if;
  if p_qty is null or p_qty <= 0 then raise exception 'จำนวนต้องมากกว่า 0'; end if;
  insert into supply_issues (ts, product_id, qty, note, staff_name) values (v_ts, p_product, p_qty, nullif(trim(p_note), ''), app.staff_name()) returning id into v_id;
  for t in select * from app.fefo_take(p_product, p_qty, v_ts, 'issue', 'ISS' || v_id, nullif(trim(p_note), '')) loop
    v_cost := v_cost + t.qty * t.unit_cost;
  end loop;
  update supply_issues set cost_total = v_cost where id = v_id;
  return v_id;
end $$;

create or replace function void_supply_issue(p_id bigint) returns void language plpgsql security definer set search_path = public as $$
declare i supply_issues; m record;
begin
  perform app.check_perm('supplies');
  select * into i from supply_issues where id = p_id for update; if not found then raise exception 'ไม่พบรายการเบิก'; end if;
  if i.status = 'void' then raise exception 'รายการนี้ถูกยกเลิกแล้ว'; end if;
  for m in select lot_id, -qty as q from stock_movements where ref_no = 'ISS' || p_id and type = 'issue' loop
    insert into stock_movements (product_id, lot_id, type, qty, ref_no, note, staff_name) values (i.product_id, m.lot_id, 'void', m.q, 'ISS' || p_id, 'ยกเลิกการเบิก', app.staff_name());
  end loop;
  update supply_issues set status = 'void', void_by = app.staff_name(), void_ts = now() where id = p_id;
end $$;

revoke execute on function issue_supply(bigint, int, text) from public;
revoke execute on function void_supply_issue(bigint) from public;
grant execute on function issue_supply(bigint, int, text) to authenticated;
grant execute on function void_supply_issue(bigint) to authenticated;
notify pgrst, 'reload schema';
